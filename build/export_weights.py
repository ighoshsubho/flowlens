"""Export the frozen weights as plain numeric JSON next to the .npz.

npz is the format the runtime loads; this JSON is the human-auditable copy:
every tensor is written out value by value, with shape and the equation it
implements.  No weights are generated here that are not already in the .npz.

Run:  python3 build/export_weights.py
"""

import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NPZ = os.path.join(ROOT, "weights", "flowlens_weights.npz")
OUT = os.path.join(ROOT, "weights", "flowlens_weights.json")

EQUATIONS = {
    "W_byte_class": "row b = onehot(class(b)); C = X @ W_byte_class",
    "W_alpha": "row b = onehot(code(b)) over 64-symbol alphabet; A = X @ W_alpha",
    "W_kw_code": "kw[k,p,:] = onehot(char p of keyword k); "
                 "score[t,k] = AND_p (spell[t,p] . kw[k,p]) and length match",
    "v_kw_len": "len(kw[k]); used only through the occupancy term",
    "v_kw_type": "1 for type keywords, 0 for 'return'",
    "v_kw_ret": "1 for 'return' only",
    "W_lex": "W_lex[t, s*NC+c] = +2 if lex_next(s,c)=t else -2; "
             "s' = argmax(W_lex @ (s (x) c))",
    "W_opener": "1 at (CODE,CODE_SLASH),(CODE_SLASH,LINE),(CODE_SLASH,BLOCK); "
                "opener = s_in^T W_opener s_out",
    "v_lex_code": "1 for the two code states",
    "v_lex_commentish": "1 for the three comment states",
    "v_cls_idchar": "1 for ALPHA, DIGIT, US",
    "v_cls_alpha": "1 for ALPHA",
    "v_cls_digit": "1 for DIGIT",
    "v_cls_us": "1 for US",
    "v_cls_quote": "1 for QUOTE, SQUOTE, BACKSLASH (string delimiters)",
    "v_cls_punct": "1 for every byte class that forms a one-byte token",
    "v_cls_op": "1 for operator byte classes",
    "W_tokF": "byte class -> token class contribution (26x13 selector)",
    "W_gsm": "W_gsm[t, s*NF+c] = +2 if grammar_next(s,c)=t else -2; "
             "s' = argmax(W_gsm @ (s (x) c))",
    "v_out_read": "1 at (EXPR,IDENT),(RET_EXPR,IDENT)",
    "v_out_assign": "1 at (AFTER_LHS,EQ)",
    "v_out_declinit": "1 at (AFTER_NAME,EQ)",
    "v_out_declterm": "1 at (AFTER_NAME,SEMI)",
    "v_out_paramwrite": "1 at (PARAM_NAME,IDENT)",
    "v_out_retend": "1 at (RET_EXPR,SEMI)",
    "v_out_barrier": "1 at every statement barrier (SEMI, braces, COMMA)",
    "v_out_anomaly": "one-token unsupported-construct detector",
    "v_out_compound": "1 at (AFTER_LHS,OP): read-modify-write marker",
    "v_anom2": "2028-wide (state (x) class (x) next-class) detector",
    "GT": "GT[i,j] = 1 iff i > j; positional greater-than relation",
}


def main():
    z = np.load(NPZ)
    out = {"format": "flowlens-weights-v1",
           "note": "every value here is the tensor the runtime loads; "
                   "generated by build/construct_weights.py",
           "tensors": {}}
    total = 0
    for k in z.files:
        a = z[k]
        total += a.size
        out["tensors"][k] = {
            "shape": list(a.shape),
            "equation": EQUATIONS.get(k, ""),
            "dense": int(a.size),
            "nonzero": int((a != 0).sum()),
            "values": a.astype(float).round(6).tolist(),
        }
    with open(OUT, "w") as f:
        json.dump(out, f)
    print("wrote", OUT, os.path.getsize(OUT), "bytes for", total, "values")


if __name__ == "__main__":
    main()
